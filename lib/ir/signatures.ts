export function u32(n: number): number {
  return n >>> 0;
}

export function bytesContain(hay: number[], needle: number[]): boolean {
  if (needle.length === 0 || hay.length < needle.length) return false;
  outer: for (let i = 0; i <= hay.length - needle.length; i++) {
    for (let j = 0; j < needle.length; j++) {
      if (hay[i + j] !== needle[j]) continue outer;
    }
    return true;
  }
  return false;
}

export function wordsToBytesLE(words: number[]): number[] {
  const out: number[] = [];
  for (const w of words) {
    const u = w >>> 0;
    out.push(u & 0xff, (u >>> 8) & 0xff, (u >>> 16) & 0xff, (u >>> 24) & 0xff);
  }
  return out;
}

export function wordsToBytesBE(words: number[]): number[] {
  const out: number[] = [];
  for (const w of words) {
    const u = w >>> 0;
    out.push((u >>> 24) & 0xff, (u >>> 16) & 0xff, (u >>> 8) & 0xff, u & 0xff);
  }
  return out;
}

export function indexOfBytes(hay: Uint8Array, needle: number[]): number {
  if (needle.length === 0 || hay.length < needle.length) return -1;
  outer: for (let i = 0; i <= hay.length - needle.length; i++) {
    for (let j = 0; j < needle.length; j++) {
      if (hay[i + j] !== needle[j]) continue outer;
    }
    return i;
  }
  return -1;
}

export function wordsContain(hay: number[], needle: number[]): boolean {
  const h = hay.map(u32);
  const n = needle.map(u32);
  return bytesContain(h, n);
}
